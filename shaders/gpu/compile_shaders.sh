#!/usr/bin/env bash
#
# Regenerates ../../video_gpu_shaders.h from the shaders in this directory.
# Run it after editing a shader and commit the result, so that building the game
# does not need these tools.
#
# Requires glslc and spirv-cross (both ship with the Vulkan SDK), dxc and xxd.
# Direct3D 12 only runs DXIL that dxc has signed, which it does when the dxil
# library sits next to it, as in the Windows SDK (bin/<version>/x64/dxc.exe).
# Set DXC to its path when that one is not first on PATH.
#
set -euo pipefail

cd "$(dirname "$0")"

OUTPUT=../../video_gpu_shaders.h
DXC=${DXC:-dxc}
SHADERS="fullscreen.vert sprite.vert palette.frag sprite.frag effect.frag overlay.frag sharp.frag
         filter_reverse.frag filter_aa.frag filter_cartoon.frag filter_crt.frag"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

# Emits one shader blob as a static const array named after the symbol.
emit() {
    local symbol=$1 file=$2
    cp "$file" "$WORK/$symbol"
    (cd "$WORK" && xxd -i "$symbol") | sed -e 's/^unsigned char/static const unsigned char/' -e 's/^unsigned int/static const unsigned int/'
}

for shader in $SHADERS; do
    symbol=${shader/./_}
    case $shader in
        *.vert) profile=vs_6_0 ;;
        *.frag) profile=ps_6_0 ;;
    esac
    glslc --target-env=vulkan1.0 -O -o "$WORK/$symbol.spv" "$shader"
    spirv-val "$WORK/$symbol.spv"
    # The binding decorations already follow SDL_GPU's slot order, and MSL only
    # numbers slots, so spirv-cross can reuse them directly.
    spirv-cross "$WORK/$symbol.spv" --msl --msl-version 20000 --msl-decoration-binding --output "$WORK/$symbol.msl"
    # For HLSL, spirv-cross turns descriptor set N into register space N, which is
    # where SDL_GPU's Direct3D 12 backend looks: space2 for fragment samplers, space1
    # and space3 for uniform buffers. Vertex inputs become TEXCOORD<location>.
    # Direct3D 12 also needs the inputs a shader declares without using (see
    # effect.frag), which glslc -O removes, so this SPIR-V is left to dxc to optimize.
    glslc --target-env=vulkan1.0 -DDXIL -o "$WORK/$symbol.dxil.spv" "$shader"
    spirv-val "$WORK/$symbol.dxil.spv"
    spirv-cross "$WORK/$symbol.dxil.spv" --hlsl --shader-model 60 --output "$WORK/$symbol.hlsl"
    "$DXC" -nologo -T "$profile" -E main -Qstrip_reflect -Fo "$WORK/$symbol.dxil" "$WORK/$symbol.hlsl"
    # A DXIL container starts with "DXBC" and a 16-byte digest, which stays zero
    # when dxc could not sign it.
    if [ "$(od -An -tx1 -j4 -N16 "$WORK/$symbol.dxil" | tr -d ' \n')" = "00000000000000000000000000000000" ]; then
        echo "$DXC left $symbol.dxil unsigned; use a dxc that has the dxil library next to it" >&2
        exit 1
    fi
done

{
    echo "/* Generated by shaders/gpu/compile_shaders.sh. Do not edit. */"
    echo
    echo "#ifndef VIDEO_GPU_SHADERS_H"
    echo "#define VIDEO_GPU_SHADERS_H"
    echo
    for shader in $SHADERS; do
        symbol=${shader/./_}
        emit "${symbol}_spv" "$WORK/$symbol.spv"
        echo
        emit "${symbol}_msl" "$WORK/$symbol.msl"
        echo
    done
    # Only Direct3D 12 takes DXIL, so other systems do not carry it.
    echo "#ifdef _WIN32"
    echo "#define VIDEO_GPU_HAS_DXIL 1"
    echo
    for shader in $SHADERS; do
        symbol=${shader/./_}
        emit "${symbol}_dxil" "$WORK/$symbol.dxil"
        echo
    done
    echo "#endif"
    echo
    echo "#endif"
} > "$OUTPUT"

echo "Wrote $OUTPUT"
